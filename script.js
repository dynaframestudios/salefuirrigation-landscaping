function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });
  document.documentElement.lang = lang === 've' ? 've' : 'en';
  localStorage.setItem('siteLang', lang);
  const label = document.getElementById('langToggleLabel');
  if (label) label.textContent = lang === 've' ? 'VE' : 'EN';
}

const langModalOverlay = document.getElementById('langModalOverlay');
const langToggle = document.getElementById('langToggle');

document.querySelectorAll('.lang-option-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    applyLanguage(btn.dataset.lang);
    langModalOverlay.classList.add('hidden');
  });
});

if (langToggle) {
  langToggle.addEventListener('click', () => {
    const current = localStorage.getItem('siteLang') === 've' ? 've' : 'en';
    applyLanguage(current === 've' ? 'en' : 've');
  });
}

const savedLang = localStorage.getItem('siteLang');
if (savedLang) {
  applyLanguage(savedLang);
  langModalOverlay.classList.add('hidden');
} else {
  applyLanguage('en');
  // Modal stays visible on first visit until a choice is made
}

// Theme Toggle (Light / Dark Mode)
const themeToggle = document.getElementById('themeToggle');
const sunIcon = themeToggle.querySelector('.fa-sun');
const moonIcon = themeToggle.querySelector('.fa-moon');

function setTheme(theme) {
  if (theme === 'dark') {
    document.body.classList.add('dark-mode');
    localStorage.setItem('theme', 'dark');
    sunIcon.style.display = 'none';
    moonIcon.style.display = 'flex';
  } else {
    document.body.classList.remove('dark-mode');
    localStorage.setItem('theme', 'light');
    sunIcon.style.display = 'flex';
    moonIcon.style.display = 'none';
  }
}

themeToggle.addEventListener('click', () => {
  const isDark = document.body.classList.contains('dark-mode');
  setTheme(isDark ? 'light' : 'dark');
});

// Load saved theme
const savedTheme = localStorage.getItem('theme');
if (savedTheme === 'dark') setTheme('dark');
else setTheme('light');

// Scroll Reveal
const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

